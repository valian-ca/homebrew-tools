package pc

import (
	"fmt"
	"maps"
	"os"
	"path/filepath"
	"slices"

	"gopkg.in/yaml.v3"
)

const ProjectFile = "process-compose.yaml"

type Process map[string]any

func ProjectProcesses(path string) ([]string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var f struct {
		Processes map[string]yaml.Node `yaml:"processes"`
	}
	if err := yaml.Unmarshal(data, &f); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return slices.Sorted(maps.Keys(f.Processes)), nil
}

// Fragment renders the file merged ahead of the project's own. It carries the
// adapters' processes and pins every log under the lane's TMPDIR, where
// `lanes logs` reads them even once the stack is stopped. The project file is
// merged after it, so the project can complete an adapter's process.
func Fragment(project []string, adapters map[string]Process, logsDir string) ([]byte, error) {
	procs := map[string]Process{}
	for name, p := range adapters {
		procs[name] = withLog(maps.Clone(p), logsDir, name)
	}
	for _, name := range project {
		if _, ok := procs[name]; !ok {
			procs[name] = withLog(Process{}, logsDir, name)
		}
	}
	doc := map[string]any{
		"version":          "0.5",
		"ordered_shutdown": true,
		"processes":        procs,
	}
	body, err := yaml.Marshal(doc)
	if err != nil {
		return nil, err
	}
	return append([]byte("# Generated by lanes. Do not edit: it is rewritten at every lanes start.\n"), body...), nil
}

// withLog writes the piece's output as plain lines, flushed as they come, so
// `lanes logs -f` follows it live.
func withLog(p Process, logsDir, name string) Process {
	p["log_location"] = filepath.Join(logsDir, name+".log")
	p["log_configuration"] = map[string]any{
		"disable_json":    true,
		"fields_order":    []string{"message"},
		"no_metadata":     true,
		"no_color":        true,
		"flush_each_line": true,
	}
	return p
}
